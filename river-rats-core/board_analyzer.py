def is_hand_vulnerable(
    hand_category: str,
    board: BoardAnalysis
) -> Tuple[bool, str]:
    """
    Check if a hand is vulnerable on this board.
    
    Args:
        hand_category: Hero's hand category
        board: BoardAnalysis result
    
    Returns:
        (is_vulnerable, reason)
    """
    cat = hand_category.lower()
    
    if cat in ('quads', 'straight_flush'):
        return False, "Invulnerable monster"
    
    if cat == 'full_house':
        return False, "Full house - very strong"
    
    if cat == 'flush' and board.is_paired:
        return True, "Flush vulnerable to full house"
    
    if cat == 'straight' and board.flush_possible:
        return True, "Straight vulnerable to flush"
    
    if cat in ('set', 'trips'):
        if board.flush_likely:
            return True, "Set/trips vulnerable to made flush"
        if board.straight_likely:
            return True, "Set/trips vulnerable to made straight"
    
    if cat == 'two_pair':
        if board.flush_possible:
            return True, "Two pair vulnerable to flush"
        if board.has_straight_possible:
            return True, "Two pair vulnerable to straight"
    
    if cat in ('top_pair', 'overpair', 'top_pair_top_kicker', 'pair', 'middle_pair', 'bottom_pair'):
        if board.danger_score >= 0.5:
            return True, f"One pair vulnerable (danger={board.danger_score:.0%})"
    
    return False, "Not particularly vulnerable"


