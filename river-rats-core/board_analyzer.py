# =============================================================================

def analyze_board(
    board: List[str],
    hero_category: str = "high_card",
    strict: bool = False
) -> BoardAnalysis:
    """
    Perform complete board analysis.
    
    Args:
        board: List of cards like ['Ks', '7h', '2d']
        hero_category: Hero's hand category (for vulnerability, optional)
        strict: If True, raises ValueError on invalid board
    
    Returns:
        BoardAnalysis with all texture and danger information
        
    Raises:
        ValueError: If strict=True and board is invalid
    """
    # Validate if strict mode
    if strict:
        validate_board(board, strict=True)
    
    if not board:
        return _empty_analysis()
    
    # Parse cards
    parsed = [parse_card(c) for c in board]
    ranks = [r for r, s in parsed if r > 0]
    suits = [s for r, s in parsed if s != 'x']
    
    # Handle empty/invalid board
    if not ranks:
        return _empty_analysis()
    
    street = _get_street(len(board))
    high_card = max(ranks)
    high_card_name = RANK_NAMES.get(high_card, "?")
    
    # ==========================================================================
    # PAIRING ANALYSIS
    # ==========================================================================
    
    rank_counts = {}
    for r in ranks:
        rank_counts[r] = rank_counts.get(r, 0) + 1
    
    pairs = [r for r, c in rank_counts.items() if c == 2]
    trips = [r for r, c in rank_counts.items() if c >= 3]
    
    is_paired = len(pairs) > 0 or len(trips) > 0
    is_double_paired = len(pairs) >= 2
    is_trips = len(trips) > 0
    pair_rank = pairs[0] if pairs else (trips[0] if trips else None)
    
    # ==========================================================================
    # SUIT ANALYSIS (Street-Aware)
    # ==========================================================================
    
    suit_counts = {}
    for s in suits:
        suit_counts[s] = suit_counts.get(s, 0) + 1
    
    max_suit_count = max(suit_counts.values()) if suit_counts else 0
    num_cards = len(board)
    
    # Street-aware suit thresholds
    is_monotone, is_two_tone, is_rainbow = _analyze_suits(
        max_suit_count=max_suit_count,
        num_cards=num_cards,
        suit_counts=suit_counts
    )
    
    flush_suit = None
    for s, count in suit_counts.items():
        if count >= 3:
            flush_suit = s
            break
    
    # Calculate flush probability
    deck_remaining = 52 - 2 - num_cards  # Assume hero has 2 cards
    flush_prob = flush_probability(max_suit_count, num_cards, deck_remaining)
    
    # ==========================================================================
    # CONNECTIVITY ANALYSIS (Improved Algorithm v2)
    # ==========================================================================
    
    unique_ranks = sorted(set(ranks))
    
    # Build rank list with wheel handling
    if 14 in unique_ranks:
        unique_ranks_with_wheel = sorted(set(unique_ranks + [1]))
    else:
        unique_ranks_with_wheel = unique_ranks
    
    connectivity = _analyze_connectivity_v2(unique_ranks_with_wheel)
    
    is_connected = connectivity['num_connected'] >= 3 or connectivity['has_oesd']
    has_straight_possible = connectivity['has_straight_possible']
    has_oesd_possible = connectivity['has_oesd']
    has_gutshot_possible = connectivity['has_gutshot']
    connectivity_score = connectivity['connectivity_score']
    
    # ==========================================================================
    # BOARD TYPE CLASSIFICATION
    # ==========================================================================
    
    board_type = _classify_board_type(
        high_card=high_card,
        is_paired=is_paired,
        pair_rank=pair_rank,
        is_monotone=is_monotone,
        is_two_tone=is_two_tone,
        is_connected=is_connected,
        has_oesd=has_oesd_possible,
        connectivity_score=connectivity_score
    )
    
    # ==========================================================================
    # STRATEGIC PARAMETERS
    # ==========================================================================
    
    strategy = _calculate_strategy_params(
        board_type=board_type,
        high_card=high_card,
        is_paired=is_paired,
        is_monotone=is_monotone,
        is_two_tone=is_two_tone,
        connectivity_score=connectivity_score,
        street=street
    )
    
    # ==========================================================================
    # DANGER ANALYSIS (Improved)
    # ==========================================================================
    
    danger = _calculate_danger_v2(
        max_suit_count=max_suit_count,
        connectivity_score=connectivity_score,
        is_paired=is_paired,
        is_trips=is_trips,
        has_straight_possible=has_straight_possible,
        has_oesd=has_oesd_possible,
        street=street,
        num_cards=num_cards,
        flush_probability=flush_prob
    )
    
    # ==========================================================================
    # POSSIBLE MADE HANDS (Ordered strongest to weakest)
    # ==========================================================================
    
    possible_hands = _get_possible_made_hands_v2(
        is_monotone=is_monotone,
        flush_possible=danger['flush_possible'],
        straight_possible=has_straight_possible,
        is_paired=is_paired,
        is_trips=is_trips,
        has_oesd=has_oesd_possible
    )
    
    # ==========================================================================
    # CONVENIENCE FLAGS
    # ==========================================================================
    
    is_dry = danger['danger_score'] < 0.3
    is_wet = danger['danger_score'] >= 0.5
    is_scary = danger['danger_score'] >= 0.6
    needs_protection = is_wet and not is_monotone
    
    # ==========================================================================
    # BUILD RESULT
    # ==========================================================================
    
    return BoardAnalysis(
        # Raw characteristics
        board_cards=board,
        street=street,
        high_card_rank=high_card,
        high_card_name=high_card_name,
        ranks=ranks,
        suits=suits,
        
        # Pairing
        is_paired=is_paired,
        is_double_paired=is_double_paired,
        is_trips=is_trips,
        pair_rank=pair_rank,
        
        # Suits
        is_monotone=is_monotone,
        is_two_tone=is_two_tone,
        is_rainbow=is_rainbow,
        flush_suit=flush_suit,
        suit_counts=suit_counts,
        max_suit_count=max_suit_count,
        
        # Connectivity
        is_connected=is_connected,
        has_straight_possible=has_straight_possible,
        has_oesd_possible=has_oesd_possible,
        has_gutshot_possible=has_gutshot_possible,
        connectivity_score=connectivity_score,
        
        # Texture
        board_type=board_type,
        pfr_advantage=strategy['pfr_advantage'],
        cbet_freq_ip=strategy['cbet_freq_ip'],
        cbet_freq_oop=strategy['cbet_freq_oop'],
        value_threshold=strategy['value_threshold'],
        bluff_threshold=strategy['bluff_threshold'],
        check_raise_freq=strategy['check_raise_freq'],
        
        # Danger
        danger_level=danger['danger_level'],
        danger_score=danger['danger_score'],
        flush_possible=danger['flush_possible'],
        flush_likely=danger['flush_likely'],
        flush_danger=danger['flush_danger'],
        flush_probability=flush_prob,
        straight_possible=has_straight_possible,
        straight_likely=connectivity_score >= 7,
        straight_danger=danger['straight_danger'],
        full_house_possible=is_paired,
        quads_possible=is_trips,
        possible_made_hands=possible_hands,
        
        # Convenience
        is_dry=is_dry,
        is_wet=is_wet,
        is_scary=is_scary,
        needs_protection=needs_protection,
    )


