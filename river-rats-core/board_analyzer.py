def simple_board_type(board_type: BoardType) -> str:
    """
    Convert BoardType enum to simple string for Oracle compatibility.
    
    The Oracle uses string-based board types ('dry', 'wet', 'paired', etc.)
    while BoardAnalysis uses the BoardType enum. This provides a canonical
    mapping to unify the two approaches.
    
    Args:
        board_type: BoardType enum value
        
    Returns:
        Simple string: 'dry', 'wet', 'paired', 'monotone', 'dynamic', 'two_tone'
    """
    mapping = {
        BoardType.DRY_HIGH: 'dry',
        BoardType.DRY_LOW: 'dry',
        BoardType.WET_CONNECTED: 'wet',
        BoardType.WET_FLUSH: 'two_tone',  # Two-tone = flush draws
        BoardType.MONOTONE: 'monotone',
        BoardType.PAIRED_HIGH: 'paired',
        BoardType.PAIRED_LOW: 'paired',
        BoardType.DYNAMIC: 'dynamic',
    }
    return mapping.get(board_type, 'dry')


