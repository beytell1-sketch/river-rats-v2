def parse_card(card: str) -> Tuple[int, str]:
    """
    Parse card string to (rank_value, suit).
    
    Args:
        card: Card string like 'Ks', 'Th', '2d'
        
    Returns:
        (rank_value, suit) where rank is 2-14 (2-A) and suit is 's','h','d','c'
        Returns (0, 'x') for invalid cards
    """
    if not card or len(card) < 2:
        return 0, 'x'
    
    rank_char = card[0].upper()
    suit_char = card[1].lower()
    
    # Validate rank
    rank = RANK_VALUES.get(rank_char, 0)
    if rank == 0:
        return 0, 'x'
    
    # Validate suit
    if suit_char not in VALID_SUITS:
        return 0, 'x'
    
    return rank, suit_char


def canonical_board(board: List[str]) -> Tuple[str, ...]:
    """
    Return canonical (normalized) board representation.
    
    Sorted by rank (high to low), then by suit for consistency.
    Use as cache key or for consistent logging.
    
    Args:
        board: List of card strings
        
    Returns:
        Tuple of normalized card strings, sorted by rank then suit
    """
    def card_sort_key(card: str) -> Tuple[int, str]:
        rank, suit = parse_card(card)
        return (-rank, suit)  # Negative rank for descending order
    
    # Normalize case and sort
    normalized = [c[0].upper() + c[1].lower() for c in board if len(c) >= 2]
    return tuple(sorted(normalized, key=card_sort_key))


def validate_board(board: List[str], strict: bool = False) -> Tuple[bool, str]:
    """
    Validate board for correctness.
    
    Args:
        board: List of card strings
        strict: If True, raises ValueError on invalid input
        
    Returns:
        (is_valid, error_message)
        
    Raises:
        ValueError: If strict=True and board is invalid
    """
    errors = []
    
    # Check board size
    if len(board) > MAX_BOARD_SIZE:
        errors.append(f"Board too large: {len(board)} cards (max {MAX_BOARD_SIZE})")
    
    # Check for valid cards
    parsed_cards = []
    for i, card in enumerate(board):
        rank, suit = parse_card(card)
        if rank == 0 or suit == 'x':
            errors.append(f"Invalid card at position {i}: '{card}'")
        else:
            parsed_cards.append((card[0].upper() + card[1].lower(), rank, suit))
    
    # Check for duplicates
    card_strs = [c[0] for c in parsed_cards]
    if len(card_strs) != len(set(card_strs)):
        duplicates = [c for c in card_strs if card_strs.count(c) > 1]
        errors.append(f"Duplicate cards: {set(duplicates)}")
    
    is_valid = len(errors) == 0
    error_msg = "; ".join(errors) if errors else ""
    
    if strict and not is_valid:
        raise ValueError(f"Invalid board: {error_msg}")
    
    return is_valid, error_msg


def _get_street(num_cards: int) -> str:
    """Determine street from number of board cards."""
    if num_cards == 0:
        return "preflop"
    elif num_cards <= 3:
        return "flop"
    elif num_cards == 4:
        return "turn"
    else:
        return "river"


