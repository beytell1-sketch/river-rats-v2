def flush_probability(
    max_suit_count: int,
    num_board_cards: int,
    deck_remaining: int = 47
) -> float:
    """
    Calculate probability opponent holds a flush given board suit count.
    
    Assumes opponent has 2 random cards from remaining deck.
    
    Args:
        max_suit_count: Number of cards of the most common suit on board
        num_board_cards: Total board cards (3/4/5)
        deck_remaining: Cards left in deck (default 47 = 52 - 2 hero - 3 board)
        
    Returns:
        Probability opponent has a flush (0.0 to 1.0)
    """
    if max_suit_count < 3:
        return 0.0
    
    # Cards remaining of the flush suit
    flush_cards_remaining = 13 - max_suit_count
    
    # Total opponent hole card combinations
    total_combos = comb(deck_remaining, 2)
    
    if total_combos == 0:
        return 0.0
    
    if max_suit_count >= 5:
        # Board has 5+ of same suit - opponent always has flush if they have any card
        # Actually need to check: opponent needs at least 1 of the flush suit to have flush
        # But with 5 on board, anyone with 1+ of that suit has flush
        # P(at least 1 flush card) = 1 - P(0 flush cards)
        non_flush_remaining = deck_remaining - flush_cards_remaining
        no_flush_combos = comb(non_flush_remaining, 2)
        return 1.0 - (no_flush_combos / total_combos)
    
    elif max_suit_count == 4:
        # Need exactly 1 flush card in hole
        # P(at least 1) = 1 - P(0)
        non_flush_remaining = deck_remaining - flush_cards_remaining
        no_flush_combos = comb(non_flush_remaining, 2)
        return 1.0 - (no_flush_combos / total_combos)
    
    elif max_suit_count == 3:
        # Need exactly 2 flush cards in hole (both suited)
        flush_combos = comb(flush_cards_remaining, 2)
        return flush_combos / total_combos
    
    return 0.0


