@dataclass
class BoardAnalysis:
    """
    Complete board analysis combining texture and danger.
    
    This is the main output - use this for all board-related decisions.
    """
    
    # =========================================================================
    # RAW BOARD CHARACTERISTICS
    # =========================================================================
    
    board_cards: List[str]           # Original cards
    street: str                      # "flop", "turn", "river"
    
    # Card info
    high_card_rank: int              # Highest card (14=A, 2=2)
    high_card_name: str              # "K", "A", etc.
    ranks: List[int]                 # All ranks on board
    suits: List[str]                 # All suits on board
    
    # Pairing
    is_paired: bool                  # Board has a pair
    is_double_paired: bool           # Board has two pairs
    is_trips: bool                   # Board has trips
    pair_rank: Optional[int]         # Rank of pair if present
    
    # Suits
    is_monotone: bool                # Flush-heavy (3+ flop, 4+ turn/river)
    is_two_tone: bool                # Two suited cards (flush draw possible)
    is_rainbow: bool                 # All different suits
    flush_suit: Optional[str]        # Which suit if flush possible
    suit_counts: Dict[str, int]      # Count per suit
    
    # Connectivity
    is_connected: bool               # 3+ cards within 4 ranks
    has_straight_possible: bool      # Straight can be made
    has_oesd_possible: bool          # Open-ended straight draw possible
    has_gutshot_possible: bool       # Gutshot possible
    connectivity_score: int          # 0-10, how connected
    
    # =========================================================================
    # TEXTURE CLASSIFICATION (Strategic)
    # =========================================================================
    
    board_type: BoardType            # Primary classification
    
    # PFR advantage
    pfr_advantage: float             # 0-1, how much board favors preflop raiser
    
    # Betting frequencies (GTO-derived)
    cbet_freq_ip: float              # Recommended c-bet frequency in position
    cbet_freq_oop: float             # Recommended c-bet frequency out of position
    
    # Range thresholds
    value_threshold: float           # Top X% of range for value betting
    bluff_threshold: float           # Bottom X% of range for bluffing
    check_raise_freq: float          # How often to check-raise
    
    # =========================================================================
    # DANGER ANALYSIS (Vulnerability)
    # =========================================================================
    
    danger_level: DangerLevel        # Categorical danger
    danger_score: float              # 0-1 combined danger score
    
    # Specific dangers
    flush_possible: bool             # Can someone have a flush?
    flush_likely: bool               # Is flush very likely (4+ suited)?
    flush_danger: float              # 0-1 flush danger score
    
    straight_possible: bool          # Can someone have a straight?
    straight_likely: bool            # Is straight very likely (4+ connected)?
    straight_danger: float           # 0-1 straight danger score
    
    full_house_possible: bool        # Can someone have a full house?
    quads_possible: bool             # Can someone have quads?
    
    # What hands are possible (ordered strongest to weakest)
    possible_made_hands: List[str]   # What made hands are possible
    
    # =========================================================================
    # CONVENIENCE FLAGS
    # =========================================================================
    
    is_dry: bool                     # Low danger, few draws
    is_wet: bool                     # High danger, many draws
    is_scary: bool                   # danger_score >= 0.6
    needs_protection: bool           # One-pair hands need to bet for protection
    
    # Fields with defaults (must come after non-default fields)
    max_suit_count: int = 0          # Highest suit count (for convenience)
    flush_probability: float = 0.0   # Combinatoric probability opponent has flush
    
    # =========================================================================
    # COMPUTED PROPERTIES
    # =========================================================================
    
    @property
    def connectivity_norm(self) -> float:
        """Normalized connectivity score (0.0-1.0)."""
        max_score = BOARD_ANALYZER_CONFIG['connectivity_max_score']
        return min(1.0, self.connectivity_score / max_score)
    
    @property
    def suit_distribution(self) -> Tuple[int, ...]:
        """
        Sorted suit distribution (highest to lowest).
        
        Examples:
            - Monotone flop (3-0-0-0): (3, 0, 0, 0)
            - Two-tone flop (2-1-0-0): (2, 1, 0, 0)
            - Rainbow flop (1-1-1-0): (1, 1, 1, 0)
            - 4-flush turn (4-0-0-0): (4, 0, 0, 0)
            - 3-1 turn (3-1-0-0): (3, 1, 0, 0)
            - 3-2 river (3-2-0-0): (3, 2, 0, 0)
        """
        counts = [self.suit_counts.get(s, 0) for s in ['s', 'h', 'd', 'c']]
        return tuple(sorted(counts, reverse=True))
    
    @property
    def suit_distribution_str(self) -> str:
        """Human-readable suit distribution string like '3-2' or '4-1'."""
        dist = self.suit_distribution
        non_zero = [str(c) for c in dist if c > 0]
        return '-'.join(non_zero) if non_zero else '0'
    
    # =========================================================================
    # HELPER METHODS
    # =========================================================================
    
    def get_simple_type(self) -> str:
        """Get simple string board type for Oracle compatibility."""
        return simple_board_type(self.board_type)
    
    def to_dict(self) -> Dict[str, Any]:
        """
        Serialize BoardAnalysis to a dictionary for logging/storage.
        
        Converts enums to strings for JSON compatibility.
        """
        result = {}
        for key, value in asdict(self).items():
            if isinstance(value, Enum):
                result[key] = value.value
            else:
                result[key] = value
        
        # Add computed properties
        result['connectivity_norm'] = self.connectivity_norm
        result['suit_distribution'] = self.suit_distribution
        result['suit_distribution_str'] = self.suit_distribution_str
        result['simple_type'] = self.get_simple_type()
        
        return result
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'BoardAnalysis':
        """
        Deserialize BoardAnalysis from a dictionary.
        
        Converts string enum values back to enums.
        """
        # Make a copy to avoid mutating input
        data = data.copy()
        
        # Convert enum strings back to enums
        if 'board_type' in data and isinstance(data['board_type'], str):
            data['board_type'] = BoardType(data['board_type'])
        if 'danger_level' in data and isinstance(data['danger_level'], str):
            data['danger_level'] = DangerLevel(data['danger_level'])
        
        # Remove computed properties (they're @property methods)
        for key in ['connectivity_norm', 'suit_distribution', 'suit_distribution_str', 'simple_type']:
            data.pop(key, None)
        
        return cls(**data)


