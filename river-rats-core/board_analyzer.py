    MONOTONE = "monotone"           # 3+ of same suit on flop, 4+ on turn/river
    PAIRED_HIGH = "paired_high"     # KK7, AA5 - High pair on board
    PAIRED_LOW = "paired_low"       # 772, 443 - Low pair on board
